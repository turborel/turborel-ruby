# frozen_string_literal: true

require "active_record"
require "active_record/connection_adapters/abstract_adapter"
require "active_record/connection_adapters/statement_pool"
require "turborel"

require_relative "turborel/arel_visitor"
require_relative "turborel/column"
require_relative "turborel/database_statements"
require_relative "turborel/defaults"
require_relative "turborel/failures"
require_relative "turborel/quoting"
require_relative "turborel/schema_creation"
require_relative "turborel/schema_statements"
require_relative "turborel/values"

# ActiveRecord, the adapter registered among its own (RULES.md D2).
module ActiveRecord
  # ActiveRecord's adapters, Turborel's among them.
  module ConnectionAdapters
    # The ActiveRecord adapter for Turborel, registered as +turborel+
    # (RULES.md D2), over the driver's plain API. Its configuration's keys
    # are the connection settings of Turborel::Client::Options, +username+
    # naming the user, or a +url+, a turborel:// URI.
    class TurborelAdapter < AbstractAdapter
      # The adapter's name.
      ADAPTER_NAME = "Turborel"

      # The SQL type of each of ActiveRecord's types.
      NATIVE_DATABASE_TYPES = {
        primary_key: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        string: { name: "CHARACTER VARYING", limit: 32_767 },
        text: { name: "CHARACTER LARGE OBJECT" },
        integer: { name: "INTEGER" },
        bigint: { name: "BIGINT" },
        float: { name: "DOUBLE PRECISION" },
        decimal: { name: "DECIMAL" },
        datetime: { name: "TIMESTAMP" },
        timestamp: { name: "TIMESTAMP" },
        time: { name: "TIME" },
        date: { name: "DATE" },
        binary: { name: "BINARY LARGE OBJECT" },
        boolean: { name: "BOOLEAN" },
        json: { name: "JSON" }
      }.freeze

      # The configuration's keys that are no connection setting.
      CONFIGURATION = %i[adapter database pool timeout url username prepared_statements statement_limit].freeze
      private_constant :CONFIGURATION

      include Turborel::Quoting
      include Turborel::DatabaseStatements
      include Turborel::SchemaStatements

      class << self
        # @return [Hash] the SQL type of each of ActiveRecord's types
        def native_database_types = NATIVE_DATABASE_TYPES

        # A connection of the plain API as +config+ says.
        #
        # @param config [Hash{Symbol => Object}]
        # @return [::Turborel::Connection]
        # @raise [ActiveRecord::ConnectionNotEstablished]
        def new_client(config)
          options = config.except(*CONFIGURATION).compact
          options[:user] = config[:username] if config[:username]
          connection = ::Turborel.connect(config[:url], **options)
          connection.autocommit = true
          connection
        rescue ::Turborel::Error => e
          raise connect_error(config, e)
        end

        # Whether a connection can be made as +config+ says.
        #
        # @return [Boolean]
        def database_exists?(config)
          new_client(config).close
          true
        rescue ConnectionNotEstablished
          false
        end

        private

        # The error of +error+, a failure to connect.
        def connect_error(config, error)
          if error.sqlstate == ::Turborel::Error::INVALID_AUTHORIZATION_SQLSTATE
            DatabaseConnectionError.username_error(config[:username] || config[:user])
          else
            ConnectionNotEstablished.new(error.message)
          end
        end

        # The ActiveRecord type of each SQL type INFORMATION_SCHEMA names,
        # the later registered matched first.
        def initialize_type_map(map)
          register_class_with_limit map, /\A(?:CHARACTER|CHAR|VARCHAR)\b/i, Type::String
          map.register_type(/\A(?:CHARACTER LARGE OBJECT|CLOB)/i, Type::Text.new)
          register_class_with_limit map, /\A(?:BINARY|VARBINARY|BINARY LARGE OBJECT|BLOB)\b/i, Type::Binary
          register_numbers(map)
          map.register_type(/\ABOOLEAN/i, Type::Boolean.new)
          map.register_type(/\ADATE\b/i, Type::Date.new)
          register_class_with_precision map, /\ATIME\b/i, Type::Time
          register_class_with_precision map, /\ATIMESTAMP\b/i, Type::DateTime
          map.register_type(/\AJSON/i, Type::Json.new)
        end

        # The types of the numbers.
        def register_numbers(map)
          map.register_type(/\ASMALLINT/i, Type::Integer.new(limit: 2))
          map.register_type(/\AINT(?:EGER)?\b/i, Type::Integer.new(limit: 4))
          map.register_type(/\ABIGINT/i, Type::Integer.new(limit: 8))
          map.register_type(/\A(?:DOUBLE PRECISION|FLOAT|REAL)/i, Type::Float.new)
          map.register_type(/\A(?:DECIMAL|NUMERIC)/i) { |sql_type| decimal(sql_type) }
        end

        # The decimal type of +sql_type+, of no scale an integer's.
        def decimal(sql_type)
          precision = extract_precision(sql_type)
          scale = extract_scale(sql_type)
          scale.nil? || scale.zero? ? Type::DecimalWithoutScale.new(precision:) : Type::Decimal.new(precision:, scale:)
        end
      end

      # The types of the SQL types.
      TYPE_MAP = Type::TypeMap.new.tap { |map| initialize_type_map(map) }

      # Prepared statements kept, each destroyed as it is dropped.
      class StatementPool < ConnectionAdapters::StatementPool
        # A pool of at most +limit+ statements of +adapter+'s connection.
        def initialize(adapter, limit)
          super(limit)
          @adapter = adapter
        end

        private

        # Destroys +statement+, on a connection still there.
        def dealloc(statement)
          connection = @adapter.instance_variable_get(:@raw_connection)
          connection.client.deallocate(statement) if connection && !connection.finished?
        end
      end

      # @return [Boolean] whether savepoints are kept: they are
      def supports_savepoints? = true

      # @return [Boolean] whether schema changes are undone by rollback:
      #   they are
      def supports_ddl_transactions? = true

      # @return [Boolean] whether foreign keys are kept: they are
      def supports_foreign_keys? = true

      # @return [Boolean] whether views are kept: they are
      def supports_views? = true

      # @return [Boolean] whether JSON columns are kept: they are
      def supports_json? = true

      # @return [Boolean] whether a datetime keeps a precision: it does
      def supports_datetime_with_precision? = true

      # @return [Boolean] whether WITH queries are read: they are
      def supports_common_table_expressions? = true

      # @return [Boolean] whether a transaction begins only as its first
      #   statement runs: it does
      def supports_lazy_transactions? = true

      # @return [Boolean] whether the connection is made and not lost
      def connected? = !@raw_connection.nil? && !@raw_connection.finished?

      # @return [Boolean] whether the server answers a Ping
      def active?
        connected? && @lock.synchronize do
          @raw_connection.client.ping
          verified!
          true
        end
      rescue ::Turborel::Error
        false
      end

      # Ends the session and closes the connection.
      #
      # @return [void]
      def disconnect!
        @lock.synchronize do
          super
          @raw_connection&.close
          @raw_connection = nil
        end
      end

      # Leaves the connection unclosed, as a forked process does.
      #
      # @return [void]
      def discard!
        @lock.synchronize do
          super
          connection = @raw_connection
          @raw_connection = nil
          connection.client.abandon if connection.is_a?(::Turborel::Connection)
        end
      end

      # The server's version, as it tells it.
      #
      # @return [AbstractAdapter::Version]
      def get_database_version
        with_raw_connection(materialize_transactions: false) do |connection|
          Version.new(connection.client.setting("SERVER_VERSION").to_s)
        end
      end

      private

      # Connects as the configuration says.
      def connect
        @raw_connection = self.class.new_client(@config)
      rescue ConnectionNotEstablished => e
        raise e.set_pool(@pool)
      end

      # Connects again, the connection there closed.
      def reconnect
        connection = @raw_connection
        @raw_connection = nil
        connection.client.abandon if connection && !connection.finished?
        connect
      end

      # The statements prepared, at most the configuration's limit.
      def build_statement_pool
        StatementPool.new(self, self.class.type_cast_config_to_integer(@config[:statement_limit]))
      end

      # How Arel's trees are written.
      def arel_visitor = Turborel::ArelVisitor.new(self)

      # The type of each SQL type.
      def type_map = TYPE_MAP

      # ActiveRecord's error of +exception+, the driver's failure.
      def translate_exception(exception, message:, sql:, binds:)
        return super unless exception.is_a?(::Turborel::Error)

        kind = Turborel::Failures.kind(exception)
        kind ? kind.new(message, sql:, binds:, connection_pool: @pool) : super
      end
    end

    register "turborel", "ActiveRecord::ConnectionAdapters::TurborelAdapter",
             "active_record/connection_adapters/turborel_adapter"

    ActiveSupport.run_load_hooks(:active_record_turboreladapter, TurborelAdapter)
  end
end
